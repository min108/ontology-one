"""Generate matching frontend/backend vocabulary from the reviewed source."""

import argparse
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "terms/zh-CN.json"


def read_source() -> dict[str, Any]:
    return json.loads(SOURCE.read_text(encoding="utf-8"))


def generated_files(source: dict[str, Any]) -> dict[str, str]:
    brand = source["brand"]
    terms = {
        key: value
        for key, value in source.items()
        if key not in {"brand", "blacklist", "length_exceptions", "technical_identifiers"}
    }
    header = "// Generated by scripts/gen_terms.py; edit terms/zh-CN.json.\n"
    py_header = "# Generated by scripts/gen_terms.py; edit terms/zh-CN.json.\nimport json\n\n"

    def python_value(name: str, value: dict[str, Any]) -> str:
        encoded = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
        # JSON remains the canonical representation; wrapped chunks keep generated Python readable to Ruff.
        chunks = [encoded[index : index + 64] for index in range(0, len(encoded), 64)]
        return (
            py_header
            + f"{name} = json.loads(\n"
            + "".join(
                "    " + (repr(chunk) if '"' in chunk else json.dumps(chunk, ensure_ascii=False)) + "\n"
                for chunk in chunks
            )
            + ")\n"
        )

    return {
        "frontend/src/i18n/brand.ts": header
        + "export const brand = {\n"
        + "".join(f"  {key}: {value!r},\n" for key, value in brand.items())
        + "} as const;\nexport const browserTitle = `${brand.product_name} · ${brand.product_descriptor}`;\n",
        "frontend/src/i18n/zh-CN/index.ts": header
        + (
            "import vocabulary from './terms.json';\n"
            "export const terms = vocabulary;\n"
            "export type Kind = keyof typeof terms.kinds;\n"
            "export type StatusDomain = keyof typeof terms.statuses;\n"
            "export type StateKind = keyof typeof terms.states;\n"
            "export type HelpTerm = keyof typeof terms.help;\n"
        ),
        "frontend/src/i18n/zh-CN/terms.json": json.dumps(terms, ensure_ascii=False, indent=2) + "\n",
        "backend/core/brand.py": python_value("BRAND", brand),
        "backend/core/terms.py": python_value("TERMS", terms),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for relative, content in generated_files(read_source()).items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    for path in stale:
        print(f"Vocabulary out of sync: {path}")
    return int(bool(stale))


if __name__ == "__main__":
    raise SystemExit(main())
