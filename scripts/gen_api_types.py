"""Generate deterministic REST v2 OpenAPI and TypeScript contracts; --check is CI-safe."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))


def openapi_schema() -> dict:
    from fastapi import FastAPI

    from backend.api.v2.routes import router
    from backend.core.brand import BRAND
    from backend.version import APP_VERSION

    app = FastAPI(title=f"{BRAND['product_name_en']} REST v2", version=APP_VERSION)
    app.include_router(router)
    return app.openapi()


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(item, ensure_ascii=False) for item in schema["enum"])
    if "anyOf" in schema or "oneOf" in schema:
        return " | ".join(ts_type(item) for item in schema.get("anyOf", schema.get("oneOf", [])))
    if "allOf" in schema:
        return " & ".join(ts_type(item) for item in schema["allOf"])
    kind = schema.get("type")
    if kind == "array":
        return "Array<" + ts_type(schema.get("items", {})) + ">"
    if kind == "object" or "properties" in schema:
        properties = schema.get("properties", {})
        required = schema.get("required", [])
        fields = [
            json.dumps(key) + ("" if key in required else "?") + ": " + ts_type(value) + ";"
            for key, value in sorted(properties.items())
        ]
        additional = schema.get("additionalProperties", False)
        if additional:
            fields.append(
                "[key: string]: " + (ts_type(additional) if isinstance(additional, dict) else "unknown") + ";"
            )
        return "{ " + " ".join(fields) + " }" if fields else "Record<string, never>"
    return {"integer": "number", "number": "number", "string": "string", "boolean": "boolean", "null": "null"}.get(
        kind, "unknown"
    )


def artifacts() -> dict[str, str]:
    schema = openapi_schema()
    definitions = schema.get("components", {}).get("schemas", {})
    lines = ["// Generated by scripts/gen_api_types.py. Do not edit.", ""]
    lines.extend("export type " + name + " = " + ts_type(value) + ";" for name, value in sorted(definitions.items()))
    return {
        "openapi.json": json.dumps(schema, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        "types.ts": "\n".join(lines) + "\n",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = ROOT / "frontend/src/api/generated"
    for name, content in artifacts().items():
        path = destination / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                print("Generated contract is stale: " + str(path.relative_to(ROOT)))
                return 1
        else:
            destination.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
